-- Portable SQL: runs on PostgreSQL (production) and H2 in PostgreSQL mode (tests).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(254)  NOT NULL,   -- always stored lower-cased
    password_hash VARCHAR(100)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    owner_id    BIGINT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE project_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_members_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_members_user    FOREIGN KEY (user_id)    REFERENCES users (id),
    CONSTRAINT uq_members_project_user UNIQUE (project_id, user_id)
);

CREATE TABLE tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT NOT NULL,
    title        VARCHAR(200) NOT NULL,
    description  VARCHAR(4000),
    priority     VARCHAR(10) NOT NULL,
    status       VARCHAR(20) NOT NULL,
    due_date     TIMESTAMP WITH TIME ZONE,
    assignee_id  BIGINT,
    created_by   BIGINT NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_tasks_project  FOREIGN KEY (project_id)  REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_id) REFERENCES users (id),
    CONSTRAINT fk_tasks_creator  FOREIGN KEY (created_by)  REFERENCES users (id),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_tasks_status   CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE'))
);

-- Indexes for the list/filter/summary queries
CREATE INDEX idx_members_user         ON project_members (user_id);
CREATE INDEX idx_tasks_project_status ON tasks (project_id, status);
CREATE INDEX idx_tasks_project_prio   ON tasks (project_id, priority);
CREATE INDEX idx_tasks_assignee       ON tasks (assignee_id);
CREATE INDEX idx_tasks_project_due    ON tasks (project_id, due_date);
CREATE INDEX idx_tasks_project_created ON tasks (project_id, created_at);